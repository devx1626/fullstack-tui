#!/usr/bin/env node
/**
 * Keymap reference generator (overhaul task 1.8 / §15 documentation deliverables).
 *
 * The command registry in `src/ui/commands.js` is the single source of truth
 * for bindings. This script renders it to `docs/keymap.md` so the published
 * reference cannot drift from the code: `tools/check.js` compares the two and
 * fails the run when they differ.
 *
 * `renderKeymapDocs()` is pure (no fs) so the check tool can import it without
 * triggering the CLI below.
 *
 * Usage:
 *   node tools/gen-keymap-docs.js           # write docs/keymap.md
 *   node tools/gen-keymap-docs.js --check   # exit 1 if docs/keymap.md is stale
 *   node tools/gen-keymap-docs.js --stdout  # print, write nothing
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { COMMANDS, displayBinding } from '../src/ui/commands.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const DOCS_PATH = path.join(ROOT, 'docs', 'keymap.md');

// Section order for the reference. Prefixes are matched in this order, so
// `history.` must not be swallowed by a broader rule.
const GROUPS = [
  ['app.', 'Global'],
  ['nav.', 'Navigation'],
  ['home.', 'Dashboard'],
  ['module.', 'Module'],
  ['lesson.', 'Lesson'],
  ['challenge.', 'Challenge'],
  ['editor.', 'Editor'],
  ['history.', 'Checkpoints'],
  ['browser.', 'Browser'],
];

function groupOf(id) {
  const hit = GROUPS.find(([prefix]) => id.startsWith(prefix));
  return hit ? hit[1] : 'Other';
}

// `displayBinding` returns the footer-hint form (bare `esc`, `up`, `cr`); the
// reference reads better with the spec's bracketed notation, so named keys are
// re-wrapped here without touching the shared display helper.
const NAMED_DISPLAY = {
  esc: 'Esc', cr: 'CR', tab: 'Tab', bs: 'BS', del: 'Del', space: 'Space',
  up: 'up', down: 'down', left: 'left', right: 'right',
  pageup: 'PageUp', pagedown: 'PageDown', home: 'Home', end: 'End',
};

function docsBinding(binding) {
  const shown = displayBinding(binding);
  if (shown.startsWith('<')) return shown; // modifier combos already bracketed
  if (shown.length === 1) return shown;    // literal characters (`q`, `G`, `4`)
  return `<${NAMED_DISPLAY[shown] || shown}>`;
}

/** Binding list → display text; an empty list is a palette-only command. */
function keysOf(cmd) {
  const list = (cmd && cmd.keys && cmd.keys.default) || [];
  if (!list.length) return '— *(palette only)*';
  return list.map((b) => `\`${docsBinding(b)}\``).join(' / ');
}

const esc = (s) => String(s).replace(/\|/g, '\\|');

/** Render the whole reference. Pure — `--check` compares against this output. */
export function renderKeymapDocs() {
  const lines = [];
  lines.push('# Keymap reference');
  lines.push('');
  lines.push('*Generated by `tools/gen-keymap-docs.js` from the command registry in');
  lines.push('`src/ui/commands.js` — do not edit by hand. `npm run check` fails when this');
  lines.push('file drifts from the registry; regenerate with `npm run keymap:docs`.*');
  lines.push('');
  lines.push(`${COMMANDS.length} commands. User overrides live in \`.data/keymap.json\` and are`);
  lines.push('merged over these defaults; unknown ids are reported, never fatal. `Screen`');
  lines.push('shows where a binding applies (`any` = global).');
  lines.push('');

  for (const [, title] of GROUPS) {
    const rows = COMMANDS.filter((c) => groupOf(c.id) === title);
    if (!rows.length) continue;
    lines.push(`## ${title}`);
    lines.push('');
    lines.push('| Command | Keys | Screen | Action |');
    lines.push('| --- | --- | --- | --- |');
    for (const cmd of rows) {
      const screen = cmd.screen ? `\`${cmd.screen}\`` : 'any';
      lines.push(`| \`${cmd.id}\` | ${keysOf(cmd)} | ${screen} | ${esc(cmd.title)} |`);
    }
    lines.push('');
  }

  return `${lines.join('\n').replace(/\n+$/, '')}\n`;
}

const invokedDirectly = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;

if (invokedDirectly) {
  const out = renderKeymapDocs();
  if (process.argv.includes('--stdout')) {
    process.stdout.write(out);
  } else if (process.argv.includes('--check')) {
    const current = fs.existsSync(DOCS_PATH) ? fs.readFileSync(DOCS_PATH, 'utf8') : '';
    if (current !== out) {
      process.stdout.write('docs/keymap.md is stale — run: npm run keymap:docs\n');
      process.exitCode = 1;
    } else {
      process.stdout.write('docs/keymap.md matches the registry\n');
    }
  } else {
    fs.writeFileSync(DOCS_PATH, out);
    process.stdout.write(`wrote ${path.relative(ROOT, DOCS_PATH)}\n`);
  }
}
