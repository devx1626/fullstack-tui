#!/usr/bin/env node
/**
 * Keymap reference generator (overhaul task 1.8 / §15 documentation deliverables).
 *
 * The command registry in `src/ui/commands.js` is the single source of truth
 * for bindings. This script renders it to `docs/keymap.md` so the published
 * reference cannot drift from the code: `tools/check.js` compares the two and
 * fails the run when they differ.
 *
 * `renderKeymapDocs()` is pure (no fs) so the check tool can import it without
 * triggering the CLI below.
 *
 * The vim cheatsheet (`docs/vim.md`) is generated from `VIM_BINDINGS` in
 * `src/editor/vim.js` the same way. That table is also driven by the test suite,
 * so a binding cannot be documented, tested and dead at the same time.
 *
 * Usage:
 *   node tools/gen-keymap-docs.js           # write docs/keymap.md + docs/vim.md
 *   node tools/gen-keymap-docs.js --check   # exit 1 if either file is stale
 *   node tools/gen-keymap-docs.js --stdout  # print, write nothing
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { COMMANDS, displayBinding } from '../src/ui/commands.js';
import { VIM_BINDINGS } from '../src/editor/vim.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const DOCS_PATH = path.join(ROOT, 'docs', 'keymap.md');
export const VIM_DOCS_PATH = path.join(ROOT, 'docs', 'vim.md');

// Section order for the reference. Prefixes are matched in this order, so
// `history.` must not be swallowed by a broader rule.
const GROUPS = [
  ['app.', 'Global'],
  ['nav.', 'Navigation'],
  ['home.', 'Dashboard'],
  ['module.', 'Module'],
  ['lesson.', 'Lesson'],
  ['challenge.', 'Challenge'],
  ['editor.', 'Editor'],
  ['history.', 'Checkpoints'],
  ['browser.', 'Browser'],
];

function groupOf(id) {
  const hit = GROUPS.find(([prefix]) => id.startsWith(prefix));
  return hit ? hit[1] : 'Other';
}

// `displayBinding` returns the footer-hint form (bare `esc`, `up`, `cr`); the
// reference reads better with the spec's bracketed notation, so named keys are
// re-wrapped here without touching the shared display helper.
const NAMED_DISPLAY = {
  esc: 'Esc', cr: 'CR', tab: 'Tab', bs: 'BS', del: 'Del', space: 'Space',
  up: 'up', down: 'down', left: 'left', right: 'right',
  pageup: 'PageUp', pagedown: 'PageDown', home: 'Home', end: 'End',
};

function docsBinding(binding) {
  const shown = displayBinding(binding);
  if (shown.startsWith('<')) return shown; // modifier combos already bracketed
  if (shown.length === 1) return shown;    // literal characters (`q`, `G`, `4`)
  return `<${NAMED_DISPLAY[shown] || shown}>`;
}

/** Binding list → display text; an empty list is a palette-only command. */
function keysOf(cmd) {
  const list = (cmd && cmd.keys && cmd.keys.default) || [];
  if (!list.length) return '— *(palette only)*';
  return list.map((b) => `\`${docsBinding(b)}\``).join(' / ');
}

const esc = (s) => String(s).replace(/\|/g, '\\|');

/** Render the whole reference. Pure — `--check` compares against this output. */
export function renderKeymapDocs() {
  const lines = [];
  lines.push('# Keymap reference');
  lines.push('');
  lines.push('*Generated by `tools/gen-keymap-docs.js` from the command registry in');
  lines.push('`src/ui/commands.js` — do not edit by hand. `npm run check` fails when this');
  lines.push('file drifts from the registry; regenerate with `npm run keymap:docs`.*');
  lines.push('');
  lines.push(`${COMMANDS.length} commands. User overrides live in \`.data/keymap.json\` and are`);
  lines.push('merged over these defaults; unknown ids are reported, never fatal. `Screen`');
  lines.push('shows where a binding applies (`any` = global).');
  lines.push('');

  for (const [, title] of GROUPS) {
    const rows = COMMANDS.filter((c) => groupOf(c.id) === title);
    if (!rows.length) continue;
    lines.push(`## ${title}`);
    lines.push('');
    lines.push('| Command | Keys | Screen | Action |');
    lines.push('| --- | --- | --- | --- |');
    for (const cmd of rows) {
      const screen = cmd.screen ? `\`${cmd.screen}\`` : 'any';
      lines.push(`| \`${cmd.id}\` | ${keysOf(cmd)} | ${screen} | ${esc(cmd.title)} |`);
    }
    lines.push('');
  }

  return `${lines.join('\n').replace(/\n+$/, '')}\n`;
}

// ---------------------------------------------------------------------------
// docs/vim.md — the vim cheatsheet
// ---------------------------------------------------------------------------

/** `ctrl-d` → `<C-d>`, `escape` → `<Esc>`, `h` → `h`. */
export function vimKeyLabel(key) {
  const named = { escape: 'Esc', enter: 'CR', space: 'Space', tab: 'Tab' };
  if (named[key]) return `<${named[key]}>`;
  const ctrl = /^ctrl-([a-z])$/.exec(key);
  if (ctrl) return `<C-${ctrl[1]}>`;
  const shiftCtrl = /^shift-ctrl-([a-z])$/.exec(key);
  if (shiftCtrl) return `<S-C-${shiftCtrl[1]}>`;
  const alt = /^alt-([a-z])$/.exec(key);
  if (alt) return `<A-${alt[1]}>`;
  return key;
}

const VIM_GROUPS = [
  ['normal', 'Normal mode'],
  ['visual', 'Visual mode'],
  ['insert', 'Insert mode'],
];

/** Render the cheatsheet. Pure — `--check` compares against this output. */
export function renderVimDocs() {
  const lines = [];
  lines.push('# Vim cheatsheet');
  lines.push('');
  lines.push('*Generated by `tools/gen-keymap-docs.js` from `VIM_BINDINGS` in');
  lines.push('`src/editor/vim.js` — do not edit by hand. `npm test` fails when this file');
  lines.push('drifts, and the same table is exercised by `tests/unit/vim.test.js`.*');
  lines.push('');
  lines.push('Vim mode is on by default (`editor.vimMode`); turning it off switches to the');
  lines.push('modeless keymap in [`keymap.md`](./keymap.md). **Ctrl+C always quits** and');
  lines.push('**Ctrl+K always opens the palette**, in every mode.');
  lines.push('');

  for (const [mode, title] of VIM_GROUPS) {
    const rows = VIM_BINDINGS.filter((b) => b.mode === mode);
    if (!rows.length) continue;
    lines.push(`## ${title}`);
    lines.push('');
    lines.push('| Keys | Command | Notes |');
    lines.push('| --- | --- | --- |');
    for (const binding of rows) {
      const keys = binding.keys.map((k) => `\`${vimKeyLabel(k)}\``).join(' ');
      lines.push(`| ${keys} | \`${binding.command}\` | ${binding.note || ''} |`);
    }
    lines.push('');
  }

  lines.push('## Two deliberate differences from standard vim');
  lines.push('');
  lines.push('1. **The caret is a boundary.** It may sit one column past the last');
  lines.push('   character, so a range is `[start, end)` rather than inclusive. That is why');
  lines.push('   a bare `v` followed by `d` deletes nothing (vim deletes one character),');
  lines.push('   and why a one-column block needs `<C-v>jd` to mean "the column the caret');
  lines.push('   is on" — the corner moves one column further out to include it.');
  lines.push('2. **A search starts strictly after the caret**, so `/x` with the caret on an');
  lines.push('   `x` moves to the next one — that is what lets `n` advance.');
  lines.push('');
  lines.push('`:w` and its friends are registry commands, not editor functions: `:w`');
  lines.push('checks your code because `challenge.check` does. Substitute replacements do');
  lines.push('not expand backreferences (`\\1` lands literally).');
  lines.push('');

  return `${lines.join('\n').replace(/\n+$/, '')}\n`;
}

const invokedDirectly = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;

if (invokedDirectly) {
  const outputs = [
    [DOCS_PATH, renderKeymapDocs()],
    [VIM_DOCS_PATH, renderVimDocs()],
  ];
  if (process.argv.includes('--stdout')) {
    for (const [, out] of outputs) process.stdout.write(out);
  } else if (process.argv.includes('--check')) {
    let stale = 0;
    for (const [file, out] of outputs) {
      const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
      const name = path.relative(ROOT, file);
      if (current !== out) {
        process.stdout.write(`${name} is stale — run: npm run keymap:docs\n`);
        stale += 1;
      } else {
        process.stdout.write(`${name} matches the registry\n`);
      }
    }
    if (stale) process.exitCode = 1;
  } else {
    for (const [file, out] of outputs) {
      fs.writeFileSync(file, out);
      process.stdout.write(`wrote ${path.relative(ROOT, file)}\n`);
    }
  }
}
